function serviceTitle(kind: Kind) {
  return SERVICES.find((s) => s.id === kind)?.title ?? "پرتره";
}

function durationFor(kind: Kind, people: number, details: ReturnType<typeof detectDetails>) {
  if (details.video) return people > 2 ? "نیم‌روز" : "۳ ساعت";
  if (kind === "fashion") return people > 3 ? "نیم‌روز" : "۳ ساعت";
  if (kind === "sport") return "۲ ساعت";
  if (kind === "art") return details.closeup || details.brand ? "۲ تا ۳ ساعت" : "۲ ساعت";
  if (people > 3) return "۳ ساعت";
  return "۱ تا ۲ ساعت";
}

