type Kind = (typeof SERVICES)[number]["id"];

function detectKind(p: string): Kind {
  const q = p.toLowerCase();
  if (/ورزش|بوکس|فیتنس|بدنساز|دونده|اسپرت|قدرت/.test(q)) return "sport";
  if (/مد|فشن|لوک|کمپین|لباس|برند پوشاک|مانکن/.test(q)) return "fashion";
  if (/استیل|محصول|عطر|مفهومی|کانسپت|هنری|آرت|سایه|نقاشی|انتزاعی/.test(q)) return "art";
  return "portrait";
}

function detectMood(p: string) {
  const q = p.toLowerCase();
  if (/تیره|تاریک|سینمایی|دراماتیک|مودی/.test(q)) return "dark";
  if (/روشن|های کی|سفید|تمیز|مینیمال|شاد/.test(q)) return "bright";
  if (/گرم|پاییز|خاکی|طلایی/.test(q)) return "warm";
  return "balanced";
}

function detectPeople(p: string) {
  const m = p.match(/(\d+|[۰-۹]+)\s*نفر/);
  if (!m) return 1;
  const n = Number(m[1].replace(/[۰-۹]/g, (d) => String("۰۱۲۳۴۵۶۷۸۹".indexOf(d))));
  return Number.isFinite(n) && n > 0 ? n : 1;
}

