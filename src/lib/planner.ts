export function generatePlan(prompt: string): string {
  const kind = detectKind(prompt);
  const mood = detectMood(prompt);
  const people = detectPeople(prompt);
  const service = SERVICES.find((s) => s.id === kind)!;
  const duration = people > 3 || kind === "fashion" ? "۳ ساعت یا نیم‌روز" : kind === "sport" ? "۲ ساعت" : "۱ تا ۲ ساعت";
  const light = LIGHT[kind][mood];
  const equipment = kind === "sport" ? "هارد لایت، دو استریپ‌لایت، دستگاه مه" : kind === "fashion" ? "اکتاباکس، استریپ‌لایت، فون رنگی" : kind === "art" ? "اسنوت، گوبو، پرچم سیاه" : "بیوتی‌دیش، رفلکتور، فون خاکستری";

  return `### خلاصهٔ کانسپت
**${prompt.trim()}**

نوع پروژه: **${service.title}** · حال‌وهوا: **${mood === "dark" ? "تیره و سینمایی" : mood === "bright" ? "روشن و تمیز" : mood === "warm" ? "گرم و پاییزی" : "متعادل"}**${people > 1 ? ` · تعداد سوژه: **${people} نفر**` : ""}

### طرح نورپردازی
${light.map((l) => `- ${l}`).join("\n")}

### لنز و تنظیمات
- ${LENS[kind]}
- ISO ۱۰۰، شاتر ۱/۲۰۰ (سینک فلاش)
- وایت‌بالانس دستی برای ثبات رنگ در کل ست

### پالت رنگی و استایل
- پالت: ${PALETTE[mood]}
- لباس: پرهیز از لوگوی بزرگ و الگوهای ریز (موآره)
- پس‌زمینه: هماهنگ با پالت، بدون رقابت با سوژه

### شات‌لیست پیشنهادی
- ${kind === "sport" ? "فریز حرکت اصلی (ضربه/پرش) ×۳ زاویه" : kind === "fashion" ? "فول‌بادی ایستاده ×۳ لوک" : kind === "art" ? "قاب اصلی با نور تک‌منبعی" : "پرترهٔ نیم‌تنه با نگاه مستقیم"}
- ${kind === "sport" ? "پرترهٔ قدرت با عرق/پودر" : kind === "fashion" ? "حرکت پارچه و واک" : kind === "art" ? "دیتیل بافت با ماکرو" : "پروفایل سه‌رخ با ریم‌لایت"}
- ${people > 1 ? "قاب گروهی + تک‌نفره‌های یکنواخت" : "کلوزآپ دیتیل (دست، چشم، اکسسوری)"}
- یک قاب آزاد و بداهه در پایان

### تجهیزات لازم در فرم رزرو
- ${equipment}

### مدت پیشنهادی
**${duration}** (شامل ۲۰ دقیقه ست‌آپ و تست نور)`;
}

export function planToNotes(prompt: string, plan: string) {
  const dur = plan.match(/### مدت پیشنهادی\n\*\*(.+?)\*\*/)?.[1] ?? "";
  return `کانسپت: ${prompt.trim()}${dur ? `\nمدت پیشنهادی برنامه‌ریز: ${dur}` : ""}\n(طرح نور از برنامه‌ریز آپ استودیو)`;
}

export function kindFromPrompt(prompt: string) {
  return detectKind(prompt);
}
