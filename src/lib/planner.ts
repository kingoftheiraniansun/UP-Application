type Kind = (typeof SERVICES)[number]["id"];
type Mood = "dark" | "bright" | "warm" | "balanced";

const normalize = (value: string) =>
  value
    .replace(/[يى]/g, "ی")
    .replace(/ك/g, "ک")
    .replace(/‌/g, " ")
    .replace(/[٠-٩]/g, (d) => String("٠١٢٣٤٥٦٧٨٩".indexOf(d)))
    .replace(/[۰-۹]/g, (d) => String("۰۱۲۳۴۵۶۷۸۹".indexOf(d)))
    .toLowerCase()
    .trim();

const has = (q: string, words: string[]) => words.some((word) => q.includes(word));

const faNumber = (n: number) => String(n).replace(/\d/g, (d) => "۰۱۲۳۴۵۶۷۸۹"[Number(d)]);

function detectKind(prompt: string): Kind {
  const q = normalize(prompt);

  if (has(q, ["بوکس", "فوتبال", "بسکتبال", "دوچرخه", "دونده", "ورزش", "ورزشی", "فیتنس", "بدنساز", "اسپرت", "رزمی", "حرکت ورزشی"])) {
    return "sport";
  }

  if (has(q, ["لوک بوک", "لوکبوک", "فشن", "مد", "لباس", "پوشاک", "مانکن", "مدلینگ", "کالکشن", "کمپین لباس", "ادیتوریال", "کت واک", "کتواک"])) {
    return "fashion";
  }

  if (has(q, ["استیل لایف", "استیل‌لایف", "محصول", "عطر", "جواهر", "زیورآلات", "لوازم آرایش", "کازمتیک", "غذا", "نوشیدنی", "بسته بندی", "بسته‌بندی", "مفهومی", "کانسپت آرت", "نقاشی", "چیدمان", "طبیعت بی جان", "طبیعت بی‌جان", "آرت"])) {
    return "art";
  }

  return "portrait";
}

function detectMood(prompt: string): Mood {
  const q = normalize(prompt);

  if (has(q, ["تیره", "تاریک", "سینمایی", "دراماتیک", "مودی", "نوآر", "کنتراست بالا", "کنتراست شدید"])) return "dark";
  if (has(q, ["پاییزی", "گرم", "خاکی", "طلایی", "کهربایی", "قهوه ای", "قهوه‌ای"])) return "warm";
  if (has(q, ["روشن", "سفید", "های کی", "تمیز", "کلین", "نور زیاد", "سفید و روشن"])) return "bright";
  return "balanced";
}

function detectPeople(prompt: string): number {
  const q = normalize(prompt);
  const digit = q.match(/(?:تیم|گروه|مدل|سوژه|نفر)\s*(\d+)/)?.[1]
    ?? q.match(/(\d+)\s*(?:نفر|مدل|سوژه)/)?.[1];

  if (digit) return Math.max(1, Math.min(20, Number(digit)));

  const words: Record<string, number> = {
    "یک": 1, "دو": 2, "سه": 3, "چهار": 4, "پنج": 5, "شش": 6, "هفت": 7, "هشت": 8,
  };
  for (const [word, number] of Object.entries(words)) {
    if (new RegExp(`(?:${word})\\s*(?:نفر|مدل|سوژه)`).test(q)) return number;
  }

  if (has(q, ["تیم", "گروهی", "گروه"])) return 4;
  return 0;
}

function detectMovement(prompt: string): boolean {
  return has(normalize(prompt), ["حرکت", "پرش", "دویدن", "ضربه", "فریز", "اکشن", "متحرک", "راه رفتن", "چرخش"]);
}

function detectWindowLight(prompt: string): boolean {
  return has(normalize(prompt), ["پنجره", "نور پنجره", "طبیعی", "روز", "آفتاب"]);
}

function detectBackground(prompt: string): "white" | "dark" | "colored" | "neutral" | "textured" {
  const q = normalize(prompt);
  if (has(q, ["سفید", "کلین", "روشن"])) return "white";
  if (has(q, ["مشکی", "سیاه", "ذغالی", "تیره"])) return "dark";
  if (has(q, ["رنگی", "رنگارنگ", "قرمز", "آبی", "سبز", "زرد", "صورتی", "بنفش"])) return "colored";
  if (has(q, ["بافت", "دیوار", "سنگ", "چوب", "تکسچر"])) return "textured";
  return "neutral";
}

function detectDetails(prompt: string) {
  const q = normalize(prompt);
  return {
    closeup: has(q, ["کلوزآپ", "کلوز اپ", "دیتیل", "جزئیات", "جزئی"]),
    video: has(q, ["ریلز", "ویدیو", "ویدئو", "فیلمبرداری"]),
    brand: has(q, ["برند", "کمپین", "تبلیغاتی", "تبلیغ"]),
    musician: has(q, ["نوازنده", "خواننده", "بازیگر"]),
  };
}

