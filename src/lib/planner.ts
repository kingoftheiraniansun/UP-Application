export function planToNotes(prompt: string, plan: string) {
  const dur = plan.match(/### مدت پیشنهادی\n\*\*(.+?)\*\*/)?.[1] ?? "";
  return `کانسپت: ${prompt.trim()}\n${dur ? `مدت پیشنهادی برنامه‌ریز: ${dur}\n` : ""}${plan}`;
}

export function kindFromPrompt(prompt: string) {
  return detectKind(prompt);
}
